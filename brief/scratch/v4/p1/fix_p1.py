def get_parent(lesson, path):
    obj = lesson
    for key in path[:-1]:
        obj = obj[key]
    return obj, path[-1]


def main():
    data = json.loads(SRC.read_text())
    lessons = {L["id"]: L for L in data["lessons"]}
    for lid, path, old, new in EDITS:
        parent, last = get_parent(lessons[lid], path)
        text = parent[last]
        n = text.count(old)
        if n != 1:
            raise SystemExit(f"{lid} {path}: old text found {n} times: {old[:70]!r}")
        parent[last] = text.replace(old, new)
    DST.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    print(f"applied {len(EDITS)} edits to {DST}")


if __name__ == "__main__":
    main()
